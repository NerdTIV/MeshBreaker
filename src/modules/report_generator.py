class ReportGenerator:
    def __init__(self, session: "SessionState"):
        self.session = session
        self._ts = time.strftime("%Y-%m-%d %H:%M:%S")

    def generate_all(self, output_dir=None):
        dest = Path(output_dir or self.session.output_dir) / "reports"
        dest.mkdir(parents=True, exist_ok=True)
        sid = self.session.session_id

        paths = {
            "json":     str(dest / f"report_{sid}.json"),
            "markdown": str(dest / f"report_{sid}.md"),
            "html":     str(dest / f"report_{sid}.html"),
        }

        self._write_json(paths["json"])
        self._write_markdown(paths["markdown"])
        self._write_html(paths["html"])

        logger.success(f"Reports written to {dest}/")
        for fmt, path in paths.items():
            logger.info(f"  {fmt.upper():8} → {path}")
        return paths

    # JSON
    def _write_json(self, path):
        report = {
            "session_id":   self.session.session_id,
            "generated":    self._ts,
            "target_mac":   self.session.target_mac,
            "target_ip":    self.session.target_ip,
            "mesh_protocol": self.session.mesh_protocol,
            "devices_found": len(self.session.devices),
            "results":       self.session.results,
        }
        with open(path, "w") as f:
            json.dump(report, f, indent=2, default=str)

    # Markdown
    def _write_markdown(self, path):
        lines = [
            "# MeshBreaker Security Report\n",
            f"**Session:** `{self.session.session_id}`  ",
            f"**Generated:** {self._ts}  \n",
            "---\n",
            "## Target",
            f"- **MAC:** `{self.session.target_mac or 'N/A'}`",
            f"- **IP:** `{self.session.target_ip or 'N/A'}`",
            f"- **Protocol:** `{self.session.mesh_protocol or 'unknown'}`",
            f"- **Devices found:** {len(self.session.devices)}\n",
            "---\n",
        ]

        # CVE matches
        cve_results = self.session.get("cve_check", [])
        if cve_results:
            lines.append("## CVE Matches\n")
            lines.append("| CVE | Severity | CVSS | Name | Matched on |")
            lines.append("|-----|----------|------|------|------------|")
            for m in cve_results:
                cve_id = m.get("cve_id", "") if isinstance(m, dict) else m.cve_id
                name   = m.get("name", "")   if isinstance(m, dict) else m.name
                sev    = m.get("severity","") if isinstance(m, dict) else m.severity
                cvss   = m.get("cvss","")     if isinstance(m, dict) else m.cvss
                mo     = m.get("matched_on",[]) if isinstance(m, dict) else m.matched_on
                lines.append(f"| {cve_id} | **{sev}** | {cvss} | {name} | {'; '.join(mo[:2])} |")
            lines.append("")

        # Protocol identification
        proto_results = self.session.get("protocol_id", [])
        if proto_results:
            lines.append("## Protocol Identification\n")
            for p in proto_results:
                name = p.get("name","") if isinstance(p, dict) else p.name
                conf = p.get("confidence",0) if isinstance(p, dict) else p.confidence
                ev   = p.get("evidence",[])  if isinstance(p, dict) else p.evidence
                lines.append(f"- **{name}** — confidence {conf}%")
                for e in ev[:3]:
                    lines.append(f"  - {e}")
            lines.append("")

        # Firmware analysis
        fw = self.session.get("firmware")
        if fw:
            lines.append("## Firmware Analysis\n")
            info = fw if isinstance(fw, dict) else fw.__dict__
            for k, v in info.items():
                if k in ("strings", "raw_samples"):
                    continue
                lines.append(f"- **{k}:** `{v}`")
            lines.append("")

        # GATT enumeration
        gatt = self.session.get("gatt")
        if gatt:
            lines.append("## GATT Enumeration\n")
            surface = gatt.get("attack_surface", []) if isinstance(gatt, dict) else []
            if surface:
                lines.append(f"**Attack surface ({len(surface)} writable characteristics):**\n")
                for item in surface:
                    lines.append(f"- `{item.get('uuid')}` handle `{item.get('handle', 0):#06x}`")
            lines.append("")

        # Fuzz results
        fuzz = self.session.get("mesh_fuzz", [])
        if fuzz:
            crashes = [r for r in fuzz if (r.get("crashed") if isinstance(r,dict) else r.crashed)]
            lines.append(f"## Mesh Fuzz Results\n")
            lines.append(f"- Payloads sent: {len(fuzz)}")
            lines.append(f"- **Crashes detected: {len(crashes)}**\n")
            for c in crashes:
                strat = c.get("strategy","") if isinstance(c,dict) else c.strategy
                pl    = c.get("payload","")  if isinstance(c,dict) else c.payload.hex()
                lines.append(f"  - Strategy `{strat}`: `{pl}`")
            lines.append("")

        lines += ["---\n", "*Generated by MeshBreaker — For authorized security research only.*\n"]
        Path(path).write_text("\n".join(lines))

    # HTML
    def _write_html(self, path):
        body_parts = []

        # Summary table
        body_parts.append("<h2>Target Summary</h2>")
        body_parts.append("<table><tr><th>Field</th><th>Value</th></tr>")
        for k, v in [("MAC", self.session.target_mac), ("IP", self.session.target_ip),
                     ("Protocol", self.session.mesh_protocol),
                     ("Devices found", len(self.session.devices))]:
            body_parts.append(f"<tr><td>{k}</td><td><code>{v or 'N/A'}</code></td></tr>")
        body_parts.append("</table>")

        # CVE table
        cve_results = self.session.get("cve_check", [])
        if cve_results:
            body_parts.append("<h2>CVE Matches</h2>")
            body_parts.append("<table><tr><th>CVE</th><th>Sev</th><th>CVSS</th><th>Name</th><th>Matched on</th></tr>")
            for m in cve_results:
                cve_id = m.get("cve_id","") if isinstance(m,dict) else m.cve_id
                sev    = m.get("severity","") if isinstance(m,dict) else m.severity
                cvss   = m.get("cvss","")     if isinstance(m,dict) else m.cvss
                name   = m.get("name","")     if isinstance(m,dict) else m.name
                mo     = m.get("matched_on",[]) if isinstance(m,dict) else m.matched_on
                cls    = sev.lower() if sev.lower() in ("critical","high","medium","low") else ""
                body_parts.append(
                    f"<tr><td>{cve_id}</td><td class='{cls}'>{sev}</td>"
                    f"<td>{cvss}</td><td>{name}</td><td>{'; '.join(mo[:2])}</td></tr>"
                )
            body_parts.append("</table>")

        html = _HTML_TEMPLATE.format(
            session_id=self.session.session_id,
            timestamp=self._ts,
            body="\n".join(body_parts),
        )
        Path(path).write_text(html)
